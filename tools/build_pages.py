#!/usr/bin/env python3
"""Build the Replay / Journal / Calculator pages: the shared head, top bar (from index.html, with the backtester's
view buttons turned into links) and footer, around each page's own body in web/static/pages/<name>.body.html.
Run after changing the top bar in index.html:  python3 tools/build_pages.py"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ST = os.path.join(ROOT, "web", "static")
PAGES = {  # name: (file, data-page, title, description, scripts)
    "practice": ("practice.html", "rp", "Blind Replay · CHRONOS", "Practise trading on real historical candles without seeing what comes next.",
                 ["vendor/lightweight-charts.standalone.production.js", "nav.js", "practice.js"]),
    "journal": ("journal.html", "jn", "Trading journal · CHRONOS", "Record your real trades and see evidence-based patterns in your own execution.",
                ["nav.js", "journal.js"]),
    "calc": ("calc.html", "calc", "Risk calculator · CHRONOS", "Position size, risk, stop distance, potential profit and loss, and R:R.",
             ["nav.js", "calc.js"]),
}


def parts():
    s = open(os.path.join(ST, "index.html"), encoding="utf-8").read()
    head = s[:s.index("<body>")]
    hs = s.index('<header class="topbar"')
    ms = s.index('<div class="more-sheet"')
    header = s[hs:s.index("</div>", ms) + 6]
    foot = s[s.index('<footer class="foot">'):s.index('<div class="toasts"')]
    a = header.index('<div class="view-seg"')
    b = header.index("</div>", a) + 6
    btns = re.findall(r'<button type="button" data-view="(\w+)"[^>]*>(.*?)</button>', header[a:b], re.S)
    href = {"test": "/", "cmp": "/?view=compare", "lib": "/?view=library"}
    nav = {"test": "bt", "cmp": "cmp", "lib": "lib"}
    links = "\n      ".join(f'<a class="tab" data-nav="{nav[v]}" href="{href[v]}">{inner}</a>' for v, inner in btns)
    header = header[:a] + links + header[b:]
    header = re.sub(r'\s*<button type="button" class="nav-res".*?</button>', "", header, flags=re.S)
    header = re.sub(r'\s*<button type="button" role="menuitem" data-more="res">.*?</button>', "", header, flags=re.S)
    header = header.replace(' aria-controls="view-ct"', "")
    # the backtester footer talks about similarity and pattern modes; the other pages get a general one
    foot = re.sub(r"<p><b>Past results only\.</b>.*?</p>\s*<p class=\"muted\">.*?</p>",
                  "<p><b>Practice and records only.</b> Replays use past market candles and journal figures come from your own entries. "
                  "Nothing here is a prediction, financial advice, or a guarantee of profit.</p>", foot, flags=re.S)
    return head, header, foot


def build():
    head, header, foot = parts()
    for name, (fn, key, title, desc, scripts) in PAGES.items():
        body = open(os.path.join(ST, "pages", name + ".body.html"), encoding="utf-8").read()
        h = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", head, flags=re.S)
        h = re.sub(r'<meta name="description" content="[^"]*">', f'<meta name="description" content="{desc}">', h)
        h = h.replace('<link rel="preload" href="/static/assets/fonts/geist-mono-var.woff2"', '<link rel="preload" href="/static/assets/fonts/geist-mono-var.woff2"')
        sc = "\n".join(f'<script src="/static/{x}"></script>' for x in scripts)
        html = (f"{h}<body data-page=\"{key}\" class=\"page-{name}\">\n<!-- generated by tools/build_pages.py: edit pages/{name}.body.html -->\n"
                f'<div class="bg-glow" aria-hidden="true"><div class="bg-grid"></div></div>\n\n{header}\n\n{body}\n{foot}'
                f'<div class="toasts" id="toasts" aria-live="assertive"></div>\n{sc}\n</body>\n</html>\n')
        open(os.path.join(ST, fn), "w", encoding="utf-8").write(html)
        print("wrote", fn)


if __name__ == "__main__":
    build()
